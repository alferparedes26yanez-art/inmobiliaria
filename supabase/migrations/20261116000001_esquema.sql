-- =====================================================================
-- Sistema inmobiliario · Migración 1: esquema (13 tablas)
-- Convenciones: minúsculas, snake_case, PK cod_*, moneda USD.
-- =====================================================================

-- 1. tipo_propiedad ---------------------------------------------------
create table public.tipo_propiedad (
  cod_tipo  smallint generated by default as identity,
  nombre    varchar(30) not null,
  constraint pk_tipo_propiedad primary key (cod_tipo),
  constraint uq_tipo_propiedad_nombre unique (nombre)
);

-- 2. sector -----------------------------------------------------------
create table public.sector (
  cod_sector  integer generated by default as identity,
  nombre      varchar(80) not null,
  ciudad      varchar(60) not null,
  constraint pk_sector primary key (cod_sector),
  constraint uq_sector_nombre_ciudad unique (nombre, ciudad)
);

-- 3. propiedad --------------------------------------------------------
create table public.propiedad (
  cod_propiedad         integer generated by default as identity,
  nombre_comercial      varchar(120) not null,
  cod_tipo              smallint not null,
  cod_sector            integer not null,
  direccion             varchar(200) not null,
  latitud               decimal(9,6) not null,
  longitud              decimal(9,6) not null,
  area_terreno_m2       decimal(10,2),           -- NULL en suites/departamentos
  area_construccion_m2  decimal(10,2),           -- NULL en terrenos
  precio_usd            decimal(12,2) not null,
  descripcion           text,
  estado                varchar(12) not null default 'disponible',
  fecha_registro        timestamptz not null default now(),
  constraint pk_propiedad primary key (cod_propiedad),
  constraint fk_propiedad_tipo foreign key (cod_tipo)
    references public.tipo_propiedad (cod_tipo) on update cascade on delete restrict,
  constraint fk_propiedad_sector foreign key (cod_sector)
    references public.sector (cod_sector) on update cascade on delete restrict,
  constraint ck_propiedad_latitud check (latitud between -90 and 90),
  constraint ck_propiedad_longitud check (longitud between -180 and 180),
  constraint ck_propiedad_area_terreno check (area_terreno_m2 > 0),
  constraint ck_propiedad_area_construccion check (area_construccion_m2 > 0),
  constraint ck_propiedad_precio check (precio_usd >= 0),
  constraint ck_propiedad_estado check (estado in ('disponible', 'reservada', 'vendida', 'inactiva'))
);

-- 4. avaluo -----------------------------------------------------------
create table public.avaluo (
  cod_avaluo        integer generated by default as identity,
  cod_propiedad     integer not null,
  fecha_avaluo      date not null,
  valor_avaluo_usd  decimal(12,2) not null,
  nivel_acabados    varchar(10),                 -- NULL en terrenos
  constraint pk_avaluo primary key (cod_avaluo),
  constraint fk_avaluo_propiedad foreign key (cod_propiedad)
    references public.propiedad (cod_propiedad) on update cascade on delete cascade,
  constraint ck_avaluo_valor check (valor_avaluo_usd >= 0),
  constraint ck_avaluo_nivel_acabados check (nivel_acabados in ('básico', 'estándar', 'lujo'))
);

-- 5. servicio_basico --------------------------------------------------
create table public.servicio_basico (
  cod_servicio  smallint generated by default as identity,
  nombre        varchar(40) not null,
  constraint pk_servicio_basico primary key (cod_servicio),
  constraint uq_servicio_basico_nombre unique (nombre)
);

-- 6. propiedad_servicio (PK compuesta) --------------------------------
create table public.propiedad_servicio (
  cod_propiedad    integer not null,
  cod_servicio     smallint not null,
  estado_servicio  varchar(12) not null,
  constraint pk_propiedad_servicio primary key (cod_propiedad, cod_servicio),
  constraint fk_propserv_propiedad foreign key (cod_propiedad)
    references public.propiedad (cod_propiedad) on update cascade on delete cascade,
  constraint fk_propserv_servicio foreign key (cod_servicio)
    references public.servicio_basico (cod_servicio) on update cascade on delete restrict,
  constraint ck_propserv_estado check (estado_servicio in ('tiene', 'factible', 'no_factible'))
);

-- 7. foto -------------------------------------------------------------
-- url: ruta del archivo dentro del bucket "fotos-propiedades" de Supabase Storage.
create table public.foto (
  cod_foto       integer generated by default as identity,
  cod_propiedad  integer not null,
  url            text not null,
  es_principal   boolean not null default false,
  orden          smallint not null default 0,
  constraint pk_foto primary key (cod_foto),
  constraint fk_foto_propiedad foreign key (cod_propiedad)
    references public.propiedad (cod_propiedad) on update cascade on delete cascade,
  constraint ck_foto_orden check (orden >= 0)
);
-- Como máximo una foto principal por propiedad.
create unique index uq_foto_principal on public.foto (cod_propiedad) where es_principal;

-- 8. cliente ----------------------------------------------------------
create table public.cliente (
  cedula          char(10) not null,
  nombre          varchar(60) not null,
  apellido        varchar(60) not null,
  telefono        char(10) not null,
  correo          varchar(120) not null,
  fecha_registro  timestamptz not null default now(),
  constraint pk_cliente primary key (cedula),
  constraint uq_cliente_correo unique (correo),
  constraint ck_cliente_cedula check (cedula ~ '^[0-9]{10}$'),
  constraint ck_cliente_telefono check (telefono ~ '^09[0-9]{8}$')
);

-- 9. interes ----------------------------------------------------------
create table public.interes (
  cod_interes          integer generated by default as identity,
  cedula               char(10) not null,
  cod_propiedad        integer not null,
  etapa                varchar(15) not null default 'interesado',
  monto_anticipo_usd   decimal(12,2),            -- NULL si la etapa no es anticipo
  fecha_actualizacion  timestamptz not null default now(),
  constraint pk_interes primary key (cod_interes),
  constraint fk_interes_cliente foreign key (cedula)
    references public.cliente (cedula) on update cascade on delete cascade,
  constraint fk_interes_propiedad foreign key (cod_propiedad)
    references public.propiedad (cod_propiedad) on update cascade on delete restrict,
  constraint uq_interes_cliente_propiedad unique (cedula, cod_propiedad),
  constraint ck_interes_etapa check (etapa in
    ('interesado', 'cita_agendada', 'visitó', 'anticipo', 'vendido', 'descartado')),
  constraint ck_interes_monto check (monto_anticipo_usd >= 0),
  constraint ck_interes_anticipo_con_monto check (etapa <> 'anticipo' or monto_anticipo_usd is not null)
);

-- 10. cita ------------------------------------------------------------
create table public.cita (
  cod_cita        integer generated by default as identity,
  cod_interes     integer not null,
  fecha           date not null,
  hora            time not null,
  estado_cita     varchar(12) not null default 'agendada',
  fecha_creacion  timestamptz not null default now(),
  constraint pk_cita primary key (cod_cita),
  constraint fk_cita_interes foreign key (cod_interes)
    references public.interes (cod_interes) on update cascade on delete cascade,
  constraint ck_cita_hora check (hora between time '09:00' and time '18:00'),
  constraint ck_cita_estado check (estado_cita in ('agendada', 'realizada', 'cancelada', 'no_asistió'))
);

-- 11. notificacion_whatsapp -------------------------------------------
create table public.notificacion_whatsapp (
  cod_notificacion  integer generated by default as identity,
  cod_cita          integer not null,
  mensaje           text not null,
  fecha_envio       timestamptz,                 -- NULL mientras está pendiente
  estado_envio      varchar(10) not null default 'pendiente',
  constraint pk_notificacion_whatsapp primary key (cod_notificacion),
  constraint fk_notificacion_cita foreign key (cod_cita)
    references public.cita (cod_cita) on update cascade on delete cascade,
  constraint ck_notificacion_estado check (estado_envio in ('pendiente', 'enviado', 'fallido'))
);

-- 12. usuario_admin ---------------------------------------------------
-- Sin contraseñas: el login lo maneja Supabase Auth (auth.users).
create table public.usuario_admin (
  usuario       varchar(30) not null,
  nombre        varchar(60) not null,
  apellido      varchar(60) not null,
  correo        varchar(120) not null,
  auth_user_id  uuid not null,
  rol           varchar(15) not null default 'asesor',
  constraint pk_usuario_admin primary key (usuario),
  constraint uq_usuario_admin_auth unique (auth_user_id),
  constraint uq_usuario_admin_correo unique (correo),
  constraint fk_usuario_admin_auth foreign key (auth_user_id)
    references auth.users (id) on delete cascade,
  constraint ck_usuario_admin_rol check (rol in ('administrador', 'asesor'))
);

-- 13. seguimiento_cliente ---------------------------------------------
create table public.seguimiento_cliente (
  cod_seguimiento  integer generated by default as identity,
  cedula           char(10) not null,
  usuario          varchar(30) not null,
  fecha            timestamptz not null default now(),
  medio            varchar(10) not null,
  mensaje          text not null,
  constraint pk_seguimiento_cliente primary key (cod_seguimiento),
  constraint fk_seguimiento_cliente foreign key (cedula)
    references public.cliente (cedula) on update cascade on delete cascade,
  constraint fk_seguimiento_usuario foreign key (usuario)
    references public.usuario_admin (usuario) on update cascade on delete restrict,
  constraint ck_seguimiento_medio check (medio in ('WhatsApp', 'llamada', 'correo'))
);

-- Índices sobre las claves foráneas y columnas de búsqueda ------------
create index ix_propiedad_tipo      on public.propiedad (cod_tipo);
