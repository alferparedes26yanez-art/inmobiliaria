-- =====================================================================
-- Sistema inmobiliario · Migración 7: ofertas especiales
-- Tabla adicional (14) para las ofertas que el administrador publica en
-- el panel público. Una oferta puede apuntar a una propiedad (y mostrar
-- su foto y un precio rebajado) o ser un anuncio general.
-- =====================================================================
create table public.oferta_especial (
  cod_oferta         integer generated by default as identity,
  titulo             varchar(80)  not null,
  descripcion        varchar(300),                 -- opcional
  etiqueta           varchar(30)  not null default 'Oferta especial',
  cod_propiedad      integer,                      -- NULL = anuncio general
  precio_oferta_usd  decimal(12,2),                -- NULL = sin precio rebajado
  fecha_inicio       date not null default current_date,
  fecha_fin          date,                         -- NULL = sin fecha de fin
  activa             boolean not null default true,
  orden              smallint not null default 0,
  fecha_registro     timestamptz not null default now(),
  constraint pk_oferta_especial primary key (cod_oferta),
  constraint fk_oferta_propiedad foreign key (cod_propiedad)
    references public.propiedad (cod_propiedad) on update cascade on delete cascade,
  constraint ck_oferta_precio check (precio_oferta_usd >= 0),
  constraint ck_oferta_precio_con_propiedad check (precio_oferta_usd is null or cod_propiedad is not null),
  constraint ck_oferta_fechas check (fecha_fin is null or fecha_fin >= fecha_inicio),
  constraint ck_oferta_orden check (orden >= 0)
);

create index ix_oferta_propiedad on public.oferta_especial (cod_propiedad);
create index ix_oferta_vigencia on public.oferta_especial (activa, fecha_inicio, fecha_fin);

alter table public.oferta_especial enable row level security;

grant select on public.oferta_especial to anon;
grant select, insert, update, delete on public.oferta_especial to authenticated;
grant all on public.oferta_especial to service_role;
grant usage, select on sequence public.oferta_especial_cod_oferta_seq to authenticated, service_role;

-- Público: solo ofertas activas, vigentes hoy (hora de Ecuador) y cuya propiedad,
-- si tiene, siga visible (el RLS de propiedad solo deja ver las disponibles).
create policy oferta_especial_lectura_publica on public.oferta_especial
  for select to anon, authenticated
  using (
    activa
    and fecha_inicio <= (now() at time zone 'America/Guayaquil')::date
    and (fecha_fin is null or fecha_fin >= (now() at time zone 'America/Guayaquil')::date)
    and (
      cod_propiedad is null
      or exists (select 1 from public.propiedad p where p.cod_propiedad = oferta_especial.cod_propiedad)
    )
  );

-- Administradores: acceso completo.
create policy oferta_especial_admin on public.oferta_especial
  for all to authenticated using (public.es_admin()) with check (public.es_admin());
